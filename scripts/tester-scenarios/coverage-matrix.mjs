#!/usr/bin/env node
// Generates TESTERS_FEATURE_MATRIX.md (every documented feature row -> the behavioural case ids that
// cover it) and, with --check, FAILS when any documented row has no case or a case cites an unknown
// row. Nothing can be added to RIZZOMA_FEATURES_STATUS.md without a case in scripts/tester-scenarios/cases.
//   node scripts/tester-scenarios/coverage-matrix.mjs            (write the matrix, report numbers)
//   node scripts/tester-scenarios/coverage-matrix.mjs --check    (exit 1 on any uncovered row)
import fs from 'node:fs';
import path from 'node:path';
import { parseFeatureRows, repoRoot } from './feature-rows.mjs';
import { loadCases } from './cases/index.mjs';

const check = process.argv.includes('--check');
const rows = parseFeatureRows();
const cases = await loadCases();
const byRow = new Map(rows.map((r) => [r.id, []]));
const unknown = [];
for (const c of cases) for (const id of c.rows || []) {
  if (!byRow.has(id)) unknown.push(`${c.id} cites unknown row ${id}`); else byRow.get(id).push(c.id);
}
const uncovered = rows.filter((r) => byRow.get(r.id).length === 0);
const covered = rows.length - uncovered.length;
const pct = ((100 * covered) / rows.length).toFixed(1);

const md = [];
md.push('# Feature coverage matrix (generated)');
md.push('');
md.push('Generated by `node scripts/tester-scenarios/coverage-matrix.mjs` from the 240-row contract in `RIZZOMA_FEATURES_STATUS.md` and the `rows:` lists of `scripts/tester-scenarios/cases/*.mjs`. Do not edit by hand.');
md.push('');
md.push(`**Rows: ${rows.length}. Covered by at least one behavioural case: ${covered} (${pct} %). Uncovered: ${uncovered.length}. Cases: ${cases.length}.**`);
md.push('');
md.push('| Row | Feature | Status in contract | Cases |');
md.push('|---|---|---|---|');
for (const r of rows) {
  const ids = byRow.get(r.id);
  md.push(`| ${r.id} | ${r.text.replace(/\|/g, '/')} | ${r.status.replace(/\|/g, '/').slice(0, 40)} | ${ids.length ? ids.join(', ') : '**NO CASE**'} |`);
}
md.push('');
fs.writeFileSync(path.join(repoRoot, 'TESTERS_FEATURE_MATRIX.md'), md.join('\n'));
console.log(`feature rows ${rows.length}, covered ${covered} (${pct}%), uncovered ${uncovered.length}, cases ${cases.length}`);
if (unknown.length) console.log(unknown.join('\n'));
if (uncovered.length) console.log('UNCOVERED: ' + uncovered.map((r) => `${r.id} ${r.text.slice(0, 40)}`).join(' ; '));
if (check && (uncovered.length || unknown.length)) { console.error('COVERAGE GATE FAILED'); process.exit(1); }
if (check) console.log('COVERAGE GATE PASSED');
